export function getBilingualCourse(uiLang, learningLang, pathOrId) {
  if (!uiLang || !learningLang || uiLang === learningLang) return null;
  const key = `${uiLang}-${learningLang}`;
  const pair = BILINGUAL_COURSES[key];
  if (!pair) return null;

  let normPath = String(pathOrId || '').toLowerCase();
  normPath = normPath.replace(/-(en|hi|te|ta|kn|1)$/g, '').replace(/-(en|hi|te|ta|kn|1)$/g, '');
  return pair[normPath] || Object.values(pair).find((c) => c.id === pathOrId || c.path === normPath) || null;
}

export function loadBilingualCoursesList(uiLang, learningLang) {
  if (!uiLang || !learningLang || uiLang === learningLang) return null;
  const key = `${uiLang}-${learningLang}`;
  const pair = BILINGUAL_COURSES[key];
  if (!pair) return null;
  return Object.values(pair);
}
